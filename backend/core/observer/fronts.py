# -*- coding: utf-8 -*-
"""Каталог фронтов наблюдателя — «углы зрения», которые чередуются.

Фронт = способ посмотреть на компанию. Ротация фронтов и есть характер
агента: сегодня он смотрит на людей, через пару дней — на застрявшие
деньги, потом — на решения без исполнителя. Однообразие = cron,
чередование = внимание.

Каталог — код, не YAML: фронтов немного, а типизация и ревью важнее
горячей подмены. Промпт-тело фронта используется в Ф3 («покажи разбор»).
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Optional


@dataclass(frozen=True)
class Front:
    id: str
    title: str          # короткое имя для виджета («Люди и нагрузка»)
    angle: str          # что именно высматривает — идёт в промпт скрина


FRONTS: List[Front] = [
    Front("people_load", "Люди и нагрузка",
          "перегруз и простой конкретных людей: кто тянет несколько тем "
          "сразу, кто выпал из встреч, на кого всё замыкается"),
    Front("stuck_money", "Застрявшие деньги",
          "сделки/клиенты/оплаты без движения: клиент упоминался и пропал, "
          "оплата «вот-вот» уже которую встречу, сделка без следующего шага"),
    Front("orphan_decisions", "Решения без исполнителя",
          "принятые решения, у которых не видно владельца, срока или "
          "следующего шага — риск, что решение забудется"),
    Front("blockers_aging", "Блокеры-долгожители",
          "блокеры, повторяющиеся из встречи во встречу: чего-то/кого-то "
          "ждут неделями, и это не двигается"),
    Front("open_tensions", "Незакрытые напряжения",
          "споры и расхождения мнений, которые всплывают повторно и не "
          "получают развязки — где команда «зависла» в несогласии"),
    Front("missed_asks", "Просьбы без ответа",
          "явные просьбы «сделай X», к которым в следующих встречах не "
          "видно возврата — ни результата, ни отказа"),
    Front("routine_to_automate", "Рутина под автоматизацию",
          "повторяющиеся ручные процессы, которые всплывают в разговорах "
          "как пожиратели времени — кандидаты на автоматизацию"),
    Front("consultant_view", "Взгляд консультанта",
          "общая картина глазами внешнего консультанта: главный риск и "
          "главная возможность, которые видны по совокупности встреч"),
    Front("watch_orders", "Поручения",
          "то, за чем человек ЯВНО попросил проследить (список поручений "
          "приложен) — любые новости по этим темам в снапшотах"),
]

_BY_ID: Dict[str, Front] = {f.id: f for f in FRONTS}


def get_front(front_id: str) -> Optional[Front]:
    return _BY_ID.get(str(front_id or "").strip())


def fronts_block() -> str:
    """Рендер каталога для промптов: `- id: angle`."""
    return "\n".join(f"- {f.id} ({f.title}): {f.angle}" for f in FRONTS)
