# -*- coding: utf-8 -*-
"""
Human-thinking discipline — ADD-AS-SKILL из claude_skills (honest-thinking,
human-thinking-mode, wisdom-mode), вшитая как ДИСЦИПЛИНА ПРОМПТА, а не как код.

Зачем именно промпт, а не код. Операции «думать как человек» (фальсификация
вместо подтверждения, удержание нескольких рамок, убийство красивой гипотезы,
числа только из проверенного) — это качество РАССУЖДЕНИЯ LLM. Их нельзя
детерминированно вычислить кодом; код-скелет уже делает своё (заземление в граф,
claim-guard, recurrence). Поэтому здесь — компактные, ДОСЛОВНО снятые с скилов
фрагменты, которые навешиваются на system-prompt тех LLM-вызовов, что работают
ПОД скелетом (интерпретация таблицы, генерация ТЗ).

Дисциплина честности про сам этот слой. Он меняет КАЧЕСТВО текста LLM, а не
детерминированный выход — значит юнит-тестами доказуема только КОМПОЗИЦИЯ
(правильный фрагмент пришит, режим уважается, пустое остаётся пустым). РЕАЛЬНУЮ
ценность (стал ли вывод честнее/полезнее) измеряет только Gate-0 на живых
кейсах — как и для всего остального скелета. Поэтому флаг по умолчанию OFF.

Источники (claude_skills-main): honest-thinking.md (5 операций порождения +
8 операций проверки), human-thinking-mode (diverge→converge, роль-из-поведения),
wisdom-mode (3 линзы: фрактал/равновесие/фаза). Сняты дословно по смыслу, без
выдумывания новых «операций».
"""
from __future__ import annotations

from typing import Optional

# --- Операции ПРОВЕРКИ (honest-thinking, дословно по смыслу) ------------------
# Берём те, что реально меняют диагностический вывод LLM. Не весь каталог —
# иначе шум; на каждый режим вешаем только релевантные (см. _MODES).
_FALSIFY = (
    "Проверяй гипотезу ОПРОВЕРГАЮЩИМ тестом, а не подтверждающим: спроси «какое "
    "наблюдение сделало бы это ЛОЖНЫМ» и поищи именно его в данных."
)
_KILL_PRETTY = (
    "Убей красивую гипотезу: если вывод элегантен, но в данных нет опоры — "
    "откажись от него, а не подгоняй факты под него."
)
_NUMBERS_VERIFIED = (
    "Числа и конкретику бери ТОЛЬКО из проверенного входа. Не видишь в данных — "
    "пиши «неизвестно», не выдумывай правдоподобное."
)
_EARNED_NOT_BUILTIN = (
    "Отличай заработанный вывод (следует из данных) от встроенного допущения "
    "(принёс с собой). Помечай, что из чего."
)
_ORACLE_HUNT = (
    "Охоться на оракула: если вывод опирается на знание, которого в данных нет — "
    "это догадка, назови её догадкой, а не фактом."
)
_LADDER_NOT_MAP = (
    "Лестница ≠ карта: цепочка рассуждений не равна реальности. Назови, на каком "
    "шаге кончились факты и начались предположения."
)

# --- Операции ПОРОЖДЕНИЯ (для творческой части — генерация ТЗ/решений) --------
_DIVERGE_CONVERGE = (
    "Сначала разойдись (несколько разных трактовок/веток), потом сойдись к одной "
    "по силе опоры в данных — не хватайся за первую."
)
_TWIN_FRICTION = (
    "Держи двойника: для своей версии построй сильнейшее возражение и проверь, "
    "переживает ли версия это трение."
)
_FRAMES = (
    "Удерживай несколько рамок (отделы/время/люди/деньги) и переключайся между "
    "ними — одна рамка прячет то, что видно из другой."
)
# wisdom-mode: линза равновесия (кто чего недо-/переделает, где Nash-ловушка) —
# несущая для кросс-отдельного взгляда.
_EQUILIBRIUM_LENS = (
    "Смотри через равновесие: где у отделов/людей стимулы тянут в РАЗНЫЕ стороны "
    "(один рекламирует — другой не может продать), там системная проблема, а не "
    "вина человека."
)

# Режим → какие дисциплины уместны. Минимально-достаточный набор на задачу.
_MODES = {
    # Интерпретация таблицы под скелетом: главное — не галлюцинировать бизнес-смысл.
    "interpret": [_FALSIFY, _NUMBERS_VERIFIED, _KILL_PRETTY, _ORACLE_HUNT],
    # Генерация ТЗ: творческая часть + не выдумать несуществующее.
    "specify": [_DIVERGE_CONVERGE, _FRAMES, _EQUILIBRIUM_LENS, _FALSIFY, _NUMBERS_VERIFIED],
    # Диагностика (слепые зоны/рассинхрон): опровержение + равновесие + лестница.
    "diagnose": [_FALSIFY, _KILL_PRETTY, _EQUILIBRIUM_LENS, _LADDER_NOT_MAP, _EARNED_NOT_BUILTIN],
}

_HEADER = "Дисциплина рассуждения (думай как сильный человек-аналитик):"


def disciplines_for(mode: str) -> list:
    """Список фрагментов-дисциплин для режима. Неизвестный режим → пусто
    (тихий no-op, не ломаем вызов)."""
    return list(_MODES.get(mode, []))


def thinking_block(mode: str) -> str:
    """Готовый текстовый блок дисциплины для режима ('' если режим неизвестен)."""
    items = disciplines_for(mode)
    if not items:
        return ""
    lines = "\n".join(f"- {it}" for it in items)
    return f"{_HEADER}\n{lines}"


def with_thinking_discipline(system_prompt: str, mode: str,
                             model_tier: Optional[str] = None) -> str:
    """Навесить дисциплину режима на существующий system-prompt.

    Чистая композиция: добавляет блок В КОНЕЦ, исходный промпт не трогает.
    Неизвестный режим или пустой блок → возвращает исходный промпт как есть
    (байт-в-байт), поэтому при выключенном флаге на call-site поведение прежнее.

    model_tier: дисциплина — это КОСТЫЛЬ для СЛАБЫХ моделей. Замер
    (docs/ru/BENCHMARK_FAITHFULNESS.md): на дешёвых (gpt-4o-mini, gemini-flash-lite)
    стабильно в плюс (TruthfulQA +0.033/+0.040, RAGTruth +0.012), а на СИЛЬНОЙ
    gpt-4o — лёгкий минус (RAGTruth F1 0.756→0.732, TruthfulQA 0.90→0.88). Поэтому
    при model_tier='premium' дисциплину НЕ навешиваем (no-op). Default None →
    поведение прежнее (применяем), продукт на дешёвых моделях не меняется.
    """
    if model_tier == "premium":
        return system_prompt or ""
    block = thinking_block(mode)
    if not block:
        return system_prompt or ""
    base = (system_prompt or "").rstrip()
    return f"{base}\n\n{block}" if base else block
