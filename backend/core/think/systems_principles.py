def explain_pattern(pattern: str) -> dict | None:
    """Паттерн (тег/kind/conflict_type) → {pathology, principle, principle_name,
    principle_short, why, bio} ИЛИ None, если уверенного соответствия нет.

    None — это сознательный выбор (claim-guard): не выдумываем причину там, где
    источник её не подтверждает."""
    key = _PATTERN_TO_PATHOLOGY.get((pattern or "").strip())
    if not key:
        return None
    path = PATHOLOGIES[key]
    pno = path["principles"][0]
    pr = PRINCIPLES[pno]
    extra = path["principles"][1:]
    return {
        "pathology": path["name"],
        "principle": pno,
        "principle_name": pr["name"],
        "principle_short": pr["short"],
        "also_principles": extra,
        "bio": path["bio"],
        "why": f"{path['name']} → нарушен Принцип {pno} «{pr['name']}»: {pr['short']}",
    }


def _pattern_of(insight: dict) -> str:
    """Извлечь паттерн-ключ из инсайта (слепая зона / рассинхрон)."""
    if not isinstance(insight, dict):
        return ""
    # слепая зона: kind=drift, либо pattern=тег сигнала
    kind = insight.get("kind")
    if kind == "drift":
        return "drift"
    for k in ("pattern", "conflict_type", "tension_type"):
        v = insight.get(k)
        if v:
            return str(v)
    return ""


def enrich_insight(insight: dict) -> dict:
    """Вернуть КОПИЮ инсайта с полем `principle` (заполнено только при уверенном
    соответствии). Аддитивно и детерминированно — без соответствия не меняем."""
    if not isinstance(insight, dict):
        return insight
    exp = explain_pattern(_pattern_of(insight))
    if not exp:
        return dict(insight)
    out = dict(insight)
    out["principle"] = exp
    return out


def enrich_insights(insights: list) -> list:
    """enrich_insight по списку. Те, где соответствия нет, проходят как есть."""
    return [enrich_insight(i) for i in (insights or [])]
