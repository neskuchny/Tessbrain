# -*- coding: utf-8 -*-
"""Тип ожидаемого ответа из вопросительного слова.

«Кто был на встрече?» спрашивает про ЛЮДЕЙ — это не свойство какого-то
корпуса, это семантика вопросительного слова: «кто/who» всегда про
человека, «когда/when» всегда про время. У нас узлы графа типизированы
(Person, Task, Decision, …), поэтому знание типа ответа позволяет каналу
графа предпочесть узлы нужного типа, а не выдавать всех соседей подряд.

История: на линейке BrainBench это знание было захардкожено в адаптере
условием «вопрос начинается с Who» — и было справедливо снято как
подгонка. Правильное место правила — здесь: общий модуль, русский язык
первым, свои тесты.

Дисциплина осторожности:
- модуль ЧИСТЫЙ: регулярные выражения, ни LLM, ни сети, ни состояния;
- паттерны СТРОГИЕ: вопросительное слово ищется в начале вопроса (после
  необязательных «а», «и», «скажи», «подскажи»), а не где угодно —
  «покажи документ, кто бы его ни писал» типом person не помечается;
- ответ None — «не знаю», и это самый частый ответ: лучше не знать,
  чем ошибиться и сдвинуть ранги.
"""
from __future__ import annotations

import re
from typing import Optional

# Необязательное вступление перед вопросительным словом.
_PREFIX = r"^\s*(?:а\s+|и\s+|скажи[,]?\s+|подскажи[,]?\s+|напомни[,]?\s+)?"

_PERSON_RES = [
    re.compile(_PREFIX + r"(кто|кого|кому|кем|с\s+кем|у\s+кого)\b", re.I),
    re.compile(_PREFIX + r"who(m|se)?\b", re.I),
]

_TIME_RES = [
    re.compile(_PREFIX + r"(когда|во\s+сколько|в\s+котором\s+часу|"
               r"с\s+какого\s+времени|до\s+какого\s+числа)\b", re.I),
    re.compile(_PREFIX + r"when\b", re.I),
]

PERSON = "person"
TIME = "time"


def expected_answer_type(query: Optional[str]) -> Optional[str]:
    """Тип ожидаемого ответа: "person" | "time" | None. Чистая функция.

    None — не «ошибка», а честное «по вопросительному слову тип не виден».
    Сейчас потребители используют только "person" (типизированный канал
    графа); "time" возвращается для темпорального ранжирования, которое
    уже умеет диапазоны (temporal_rerank), — задел, не мёртвый код.
    """
    q = (query or "").strip()
    if len(q) < 4:
        return None
    for p in _PERSON_RES:
        if p.search(q):
            return PERSON
    for p in _TIME_RES:
        if p.search(q):
            return TIME
    return None


__all__ = ["expected_answer_type", "PERSON", "TIME"]
