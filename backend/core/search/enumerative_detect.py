# -*- coding: utf-8 -*-
"""Детектор перечислительных запросов: «покажи всех, кто…» — не для вектора.

Причина (arXiv 2508.21038, ICLR'26): число top-k подмножеств документов,
которые одновекторный эмбеддинг способен вернуть, ограничено размерностью
вектора — это геометрия, её не лечат ни данными, ни размером модели.
Ровно тот класс запросов, где предел бьёт больнее всего, — перечисление
и пересечение («все, кто…», «кто участвовал и в A, и в B», «сколько…»):
на датасете LIMIT лучшие эмбеддеры не решают даже 46 документов.

У нас смысловые связи хранятся структурно — в графе, и для перечисления
он точнее вектора по построению. Этот модуль распознаёт такие запросы,
чтобы поиск поднял вес графового канала.

Дисциплина осторожности:
- детектор ЧИСТЫЙ: регулярные выражения, ни LLM, ни сети, ни состояния;
- паттерны СТРОГИЕ: лучше пропустить перечисление (останется прежнее
  поведение), чем ложно сработать на обычном вопросе и сдвинуть ранги;
- сработка НИЧЕГО не отключает — вектор и BM25 продолжают искать,
  меняются только веса слияния (и это тоже за выключателем).
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Optional

# Перечисление: явная просьба списка/всех.
_LIST_RES = [
    re.compile(r"\b(покажи|выведи|перечисли|назови|собери|дай)\s+(мне\s+)?(вс[ех|ё|е]|список|перечень)\b", re.I),
    re.compile(r"\b(список|перечень)\s+(всех|вс[её])\b", re.I),
    re.compile(r"\bвсе[хм]?\s*,?\s*кто\b", re.I),
    re.compile(r"\bкакие\s+(задачи|решения|проекты|риски|встречи|документы|люди|сотрудники)\b", re.I),
    re.compile(r"\b(list|show)\s+(all|every)\b", re.I),
    re.compile(r"\ball\s+(people|tasks|decisions|projects)\s+(who|that|with)\b", re.I),
]

# Подсчёт и агрегация: ответ — число, собранное из НЕСКОЛЬКИХ мест.
# Живой прогон LongMemEval показал: именно этот класс проваливается на
# top-K ретриве (multi-session 0.5) — сумма/счёт разбросаны по разговорам,
# и top-K по релевантности не достаёт все вхождения.
_COUNT_RES = [
    re.compile(r"\bсколько\s+(человек|людей|сотрудников|задач|решений|проектов|встреч|рисков|раз)\b", re.I),
    re.compile(r"\bсколько\s+(всего|суммарно|в\s+общей\s+сложности|в\s+итоге)\b", re.I),
    re.compile(r"\b(суммарно|в\s+общей\s+сложности|общая\s+сумма|итого)\b", re.I),
    re.compile(r"\b(как\s+долго|сколько\s+времени|с\s+какого\s+времени)\b", re.I),
    re.compile(r"\bhow\s+(many|much)\b", re.I),
    re.compile(r"\b(in\s+total|total\s+amount|altogether)\b", re.I),
    re.compile(r"\bhow\s+long\s+(have|has|did|do|was|were)\b", re.I),
]

# Пересечение: «и в A, и в B» / «кто … и … и …» — комбинаторика,
# самое сердце предела размерности.
_INTERSECT_RES = [
    re.compile(r"\bкто\b.{0,80}?\bи\s+(в|с|над|по)\b.{0,80}?\bи\s+(в|с|над|по)\b", re.I),
    re.compile(r"\b(участвовал|работал|связан)[аи]?\s+(и\s+)?(в|с|над)\b.{0,60}\bи\s+(в|с|над)\b", re.I),
    re.compile(r"\bboth\b.{0,60}\band\b", re.I),
]

# Реляционный вопрос БЕЗ слова «все»: «кто был на встрече», «кто отвечает
# за деплой», «who attended the kickoff». Ответ — множество связей одной
# сущности, то есть ровно то, что лежит в графе структурно. Раньше детектор
# требовал «все, кто» — а живые люди слово «все» не говорят: это показал
# и разбор реальных запросов к продукту, и прогон на чужой линейке
# BrainBench (145 вопросов вида «Who attended X?», детектор молчал на всех).
# Паттерны строгие: «кто/who + глагол отношения» либо «кто + в/на/из»;
# голое «кто знает?» без глагола отношения не ловим.
# Выключатель RELATIONAL_DETECT=off возвращает прежний детектор байт-в-байт.
_RELATIONAL_RES = [
    re.compile(r"\bкто\s+(из\s+\S+\s+)?(был[аи]?|участв\w+|присутствов\w+|"
               r"работа\w+|отвеча\w+|руковод\w+|ведёт|вёл|вела|вели|"
               r"принима\w+|принял[аи]?|инвестир\w+|консультиру\w+|"
               r"совету\w+|входит|входил[аи]?|состоит|состоял[аи]?|"
               r"занима\w+|готовит|готовил[аи]?|назнач\w+|предлож\w+|"
               r"реш\w+|голосов\w+)\b", re.I),
    re.compile(r"\bкто\s+(в|на|из|за|у)\s+\S+", re.I),
    re.compile(r"\b(кого|кому)\s+(назнач\w+|выбрал\w+|поставил\w+|"
               r"пригласил\w+|отправил\w+|порекомендов\w+)\b", re.I),
    re.compile(r"\bwho\s+(is|are|was|were|attend(?:s|ed)?|work(?:s|ed)?|"
               r"invest(?:s|ed)?|advis(?:es|ed)|found(?:s|ed)|lead(?:s)?|led|"
               r"manag(?:es|ed)|join(?:s|ed)|serv(?:es|ed)|run(?:s)?|ran|"
               r"own(?:s|ed)?|report(?:s|ed)?|approv(?:es|ed)|review(?:s|ed))\b",
               re.I),
    re.compile(r"\bwho\s+(at|in|on|from)\s+\S+", re.I),
]


def _relational_enabled() -> bool:
    """RELATIONAL_DETECT=off — прежний детектор байт-в-байт."""
    import os
    return (os.getenv("RELATIONAL_DETECT", "on") or "on").strip().lower() in (
        "1", "on", "true", "yes")


@dataclass
class EnumVerdict:
    is_enumerative: bool
    kind: str = ""          # list | count | intersect
    matched: str = ""       # какой паттерн сработал — для отладки/метрики

    def __bool__(self) -> bool:  # удобство: if detect(q): ...
        return self.is_enumerative


def detect(query: Optional[str]) -> EnumVerdict:
    """Перечислительный ли запрос. Чистая функция, не raises.

    Порядок проверки: пересечение → подсчёт → список → реляционный.
    Пересечение первым: оно самое комбинаторное, и запрос «сколько человек
    работали и в A и в B» важнее пометить как intersect, чем как count.
    Реляционный последним: он самый широкий, пусть выигрывают точные метки.
    """
    q = (query or "").strip()
    if len(q) < 8:
        return EnumVerdict(False)
    groups = [("intersect", _INTERSECT_RES),
              ("count", _COUNT_RES),
              ("list", _LIST_RES)]
    if _relational_enabled():
        groups.append(("relational", _RELATIONAL_RES))
    for kind, patterns in groups:
        for p in patterns:
            m = p.search(q)
            if m:
                return EnumVerdict(True, kind=kind, matched=m.group(0)[:60])
    return EnumVerdict(False)


__all__ = ["EnumVerdict", "detect"]
