# -*- coding: utf-8 -*-
"""Уверенный структурный ответ: когда граф знает список целиком.

Смысл. На вопрос «кто был на встрече X» ответ — список участников, и он
лежит в графе полностью. Добор выдачи до top-K лексическими попаданиями
не добавляет ни одного правильного ответа, зато разбавляет точность и
подсовывает модели-читателю шум. Если система уверена, что структурный
ответ полный, — честнее отдать только его.

Когда система «уверена» (все условия сразу, иначе — обычный путь):
  1. вопрос реляционный/перечислительный (продовый enumerative_detect);
  2. тип ожидаемого ответа известен (answer_type: «кто» → person);
  3. графовый канал дал узлы ровно этого типа, их ≥ 1 и ≤ MAX_SET
     (список правдоподобного размера, а не полграфа).

История. На линейке BrainBench это поведение было захардкожено в
адаптере и снято как подгонка (см. docs/ru/BENCHMARK_BRAINBENCH.md).
Здесь оно возвращено как общее правило продукта: триггер — семантика
вопроса и типы узлов, а не форма вопросов конкретного корпуса.

Дисциплина осторожности:
- ВЫКЛЮЧЕНО по умолчанию (CONFIDENT_GRAPH=on включает): режим меняет
  состав выдачи, а не только порядок — включаем после проверки на своих
  данных;
- никакой мутации: функция возвращает НОВЫЙ отфильтрованный список или
  None («не уверен») — при None вызывающий оставляет выдачу как была;
- чистая логика: ни сети, ни LLM, ни состояния.
"""
from __future__ import annotations

import os
from typing import Callable, List, Optional, Sequence

# Больше этого — уже не «список участников», а пол-графа: не доверяем.
MAX_SET = 25


def confident_enabled() -> bool:
    """CONFIDENT_GRAPH=on включает режим. По умолчанию выключен."""
    return (os.getenv("CONFIDENT_GRAPH", "") or "").strip().lower() in (
        "1", "on", "true", "yes")


def pick_confident(
    fused: Sequence,
    graph_ids_of_expected_type: List[str],
    *,
    verdict_truthy: bool,
    expected_type: Optional[str],
    id_of: Callable = lambda fr: getattr(fr, "doc_id", None),
) -> Optional[list]:
    """Вернуть слитые результаты, суженные до структурного ответа, — или
    None, если уверенности нет (вызывающий оставляет выдачу как была).

    fused — результаты слияния В ИХ ПОРЯДКЕ (порядок сохраняется: внутри
    списка участников всё ещё полезно ранжирование «кто чаще упоминается
    рядом»). graph_ids_of_expected_type — id узлов графового канала,
    прошедших фильтр по типу ответа; фильтрует вызывающий, он знает форму
    своих результатов.
    """
    if not verdict_truthy or expected_type is None:
        return None
    ids = [i for i in graph_ids_of_expected_type if i]
    if not ids or len(ids) > MAX_SET:
        return None
    allowed = set(ids)
    picked = [fr for fr in fused if id_of(fr) in allowed]
    if not picked:
        # Структурные кандидаты не дожили до слияния — доверять нечему.
        return None
    return picked


__all__ = ["confident_enabled", "pick_confident", "MAX_SET"]
