// Реквизиты и данные для юридических страниц (оферта + соглашение).
//
// ┌───────────────────────────────────────────────────────────────────────┐
// │  ВПИШИ РЕАЛЬНЫЕ РЕКВИЗИТЫ ПЕРЕД АКТИВАЦИЕЙ ПЛАТЕЖЕЙ.                     │
// │  ЮKassa проверяет публичную оферту при подключении и требует, чтобы     │
// │  реквизиты продавца (ИНН/ОГРН(ИП)/юр.адрес/банк) совпадали с анкетой.   │
// │  Плейсхолдеры вида «__…__» НЕЛЬЗЯ оставлять в проде.                     │
// └───────────────────────────────────────────────────────────────────────┘
//
// Единственный источник правды: и /offer, и /terms читают отсюда — правишь
// в одном месте.

type Plan = { key: string; title: string; month: number | null; year: number | null; note: string }

/** Разбор сетки тарифов из настройки. Никогда не бросает: страница
 *  оферты не должна падать из-за опечатки в переменной окружения. */
function parsePlans(raw: string | undefined): Plan[] {
  if (!raw) return []
  try {
    const parsed = JSON.parse(raw)
    return Array.isArray(parsed) ? (parsed as Plan[]) : []
  } catch {
    return []
  }
}

